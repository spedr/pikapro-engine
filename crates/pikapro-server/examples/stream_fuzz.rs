#[derive(Clone, Copy, PartialEq, Eq)]
enum Mode {
    Lines,
    Batch,
    Mixed,
}

struct Args {
    format: Format,
    /// A Showdown format id to start instead of the preset's.
    formatid: Option<String>,
    battles: u64,
    seed: u64,
    sodium: bool,
    mode: Mode,
    channels: u64,
    show: usize,
    record: Option<PathBuf>,
    rerecord: Option<PathBuf>,
    hidden: bool,
    /// Hand-written edge cases instead of random scripts.
    edge: bool,
    /// Scripts also run through both command-line tools.
    cli: u64,
    /// Players bring a seed for the random battles' generator, not a team.
    generated: bool,
}

fn args() -> Args {
    let mut a = Args {
        format: Format::champions_vgc(),
        formatid: None,
        battles: 50,
        seed: 2_100_000,
        sodium: false,
        mode: Mode::Mixed,
        channels: 4,
        show: 3,
        record: None,
        rerecord: None,
        hidden: false,
        edge: false,
        cli: 0,
        generated: false,
    };
    let mut it = pikapro_conformance::cli::Args::from_env();
    while let Some(flag) = it.next_flag() {
        let flag = flag.as_str();
        match flag {
            "--format" => a.format = it.format(flag),
            "--formatid" => a.formatid = Some(it.value(flag)),
            "--battles" => a.battles = it.num(flag),
            "--seed" => a.seed = it.num(flag),
            "--sodium" => a.sodium = true,
            "--hidden" => a.hidden = true,
            "--edge" => a.edge = true,
            "--mode" => {
                a.mode = match it.value(flag).as_str() {
                    "lines" => Mode::Lines,
                    "batch" => Mode::Batch,
                    _ => Mode::Mixed,
                }
            }
            "--channels" => a.channels = it.num(flag),
            "--show" => a.show = it.num(flag) as usize,
            "--record" => a.record = Some(PathBuf::from(it.value(flag))),
            "--rerecord" => a.rerecord = Some(PathBuf::from(it.value(flag))),
            "--cli" => a.cli = it.num(flag),
            "--generated" => a.generated = true,
            other => panic!("unknown argument {other}"),
        }
    }
    a
}

/// A generated case.
struct Case {
    name: String,
    /// A custom game: Showdown's `|debug|` lines are dropped
    /// ([`script_debug`]).
    debug: bool,
    seed: u64,
    keep_alive: bool,
    replay: Option<&'static str>,
    commands: Vec<String>,
    writes: Vec<String>,
    channel_writes: Option<Vec<(String, String)>>,
}

/// Whether a script starts a custom game (Showdown's `format.debug`), whose
/// `|debug|` lines are dropped: a `>start` whose `formatid` resolves to
/// one. Read from the script itself, so `--record` and `--rerecord` agree
/// on every transcript.
fn script_debug(writes: &[String]) -> bool {
    writes.iter().flat_map(|w| w.split('\n')).filter_map(|l| l.strip_prefix(">start ")).any(|options| {
        Json::parse(options).ok().is_some_and(|o| {
            o.get("formatid").and_then(Json::as_str).and_then(pikapro_server::format::resolve).is_some_and(|f| f.debug)
        })
    })
}

fn random_seed_text(rng: &mut BattleRng, sodium: bool) -> String {
    if sodium {
        let words = match rng.random(4) {
            0 => 8,
            1 => 2,
            _ => 4,
        };
        let hex: String = (0..words).map(|_| format!("{:08x}", rng.next_u32())).collect();
        format!("sodium,{hex}")
    } else {
        let hex: String = (0..4).map(|_| format!("{:04x}", rng.random(1 << 16))).collect();
        format!("gen5,{hex}")
    }
}

/// Generates a script by driving pikapro-server's stream.
fn generate(
    format: &Format,
    formatid: Option<&str>,
    seed: u64,
    sodium: bool,
    hidden: bool,
    generated: bool,
) -> Vec<String> {
    let mut rng = BattleRng::new(Seed::fast(seed));
    let mut teams = [random_team(format, &mut rng), random_team(format, &mut rng)];
    if hidden {
        force_hidden(format, &mut teams, &mut rng);
    }
    let probe_rate = if hidden { 40 } else { 20 };
    // Now and then p2 joins first (its genders are drawn first), or the
    // RNG is reseeded between the players.
    let reverse = rng.random(8) == 0;
    let reseed_between = rng.random(12) == 0;
    let nicknames = random_nicknames(&teams, seed);
    let shiny = random_shiny(&teams, seed);
    // One set in four has a Poke Ball, which requests show; drawn from its
    // own stream so the rest of the scenario doesn't change.
    let mut ball_rng = BattleRng::new(Seed::fast(seed ^ 0x6261_6c6c));
    let balls: Vec<&str> = format.dex.items.iter().filter(|i| i.is_pokeball).map(|i| i.name).collect();
    let sheets: Vec<TeamSheet> = (0..2)
        .map(|s| TeamSheet {
            team: teams[s].clone(),
            extras: (0..teams[s].sets.len())
                .map(|i| SetExtras {
                    name: nicknames[s].get(i).cloned().unwrap_or_default(),
                    shiny: shiny[s].get(i).copied().unwrap_or(false),
                    pokeball: match ball_rng.random(4) {
                        0 => balls[ball_rng.random(balls.len() as u32) as usize].to_string(),
                        _ => String::new(),
                    },
                    ..SetExtras::default()
                })
                .collect(),
        })
        .collect();
    let mut names: Vec<Vec<String>> = sheets.iter().map(|s| s.nicknames(format)).collect();
    // A generated team's Pokémon go by their base species.
    if generated {
        names = vec![vec![String::new(); 6]; 2];
    }
    // The generator's seed of each player, drawn from its own stream.
    let mut team_seed_rng = BattleRng::new(Seed::fast(seed ^ 0x7465_616d));
    let team_seeds: Vec<String> = (0..2)
        .map(|_| {
            let sodium = team_seed_rng.random(2) == 0;
            random_seed_text(&mut team_seed_rng, sodium)
        })
        .collect();
    let packed: Vec<String> = sheets.iter().map(|s| pack_team(s, format)).collect();
    // Sometimes another spelling Showdown reads as the same format (the
    // preset's own id is not one: Showdown doesn't know it).
    let formatid = if let Some(id) = formatid {
        id.to_string()
    } else if rng.random(6) == 0 {
        match format.id {
            "championsvgc" => "[Gen 9 Champions] VGC 2026 Reg M-C",
            "championsbss" => "[Gen 9 Champions] BSS Reg M-C",
            "gen9vgc" => "Gen9DoublesCustomGame@@@Adjust Level Down = 50,Picked Team Size = 4",
            "gen9doubles" => "[Gen 9] Doubles Custom Game@@@!Team Preview",
            "gen9singles" => " gen9customgame@@@!Team Preview",
            "gen9ou" => "[Gen 9] OU",
            "gen9randombattle" => "[Gen 9] Random Battle",
            "gen9randomdoublesbattle" => "[Gen 9] Random Doubles Battle",
            other => panic!("no other spelling of {other}'s Showdown format"),
        }
        .to_string()
    } else {
        showdown_format(format).expect("a Showdown format").to_string()
    };
    let seed_text = random_seed_text(&mut rng, sodium);
    let player_names = ["Alice", "Bob"];
    let player = |rng: &mut BattleRng, s: usize| -> String {
        if generated {
            let extra = if rng.random(6) == 0 { ",\"avatar\":\"lucas\"" } else { "" };
            return format!("{{\"name\":{},\"seed\":{}{extra}}}", quote(player_names[s]), quote(&team_seeds[s]));
        }
        let team = if rng.random(5) == 0 {
            Json::Array(sets::unpack(&packed[s]).expect("our packed team unpacks")).stringify()
        } else {
            quote(&packed[s])
        };
        let extra = match rng.random(6) {
            0 => ",\"avatar\":\"lucas\"",
            1 => ",\"rating\":1500",
            _ => "",
        };
        format!("{{\"name\":{},\"team\":{team}{extra}}}", quote(player_names[s]))
    };
    let rated = match rng.random(20) {
        0 => ",\"rated\":\"Rated battle\"",
        1 => ",\"rated\":true",
        2 => ",\"rated\":\"Tournament battle\"",
        _ => "",
    };
    let mut commands = Vec::new();
    if rng.random(8) == 0 {
        let (p1, p2) = (player(&mut rng, 0), player(&mut rng, 1));
        commands.push(format!(
            ">start {{\"formatid\":{},\"seed\":{}{rated},\"p1\":{p1},\"p2\":{p2}}}",
            quote(&formatid),
            quote(&seed_text)
        ));
    } else {
        commands.push(format!(">start {{\"formatid\":{},\"seed\":{}{rated}}}", quote(&formatid), quote(&seed_text)));
        if rng.random(10) == 0 {
            commands.push(">chat before the players".into());
        }
        let order = if reverse { [1, 0] } else { [0, 1] };
        for (k, s) in order.into_iter().enumerate() {
            if k == 1 && reseed_between {
                commands.push(format!(">reseed {}", random_seed_text(&mut rng, sodium)));
            }
            commands.push(format!(">player p{} {}", s + 1, player(&mut rng, s)));
            if rng.random(20) == 0 {
                commands.push(format!(">player p{} {{\"name\":{}}}", s + 1, quote(player_names[s])));
            }
        }
    }
    let mut stream = BattleStream::new(transcript::options(false, None));
    for c in &commands {
        stream.write(c).unwrap_or_else(|e| panic!("seed {seed}: {c}: {e}"));
    }
    let mut steps = 0;
    while !stream.battle_ended() && steps < 3000 {
        steps += 1;
        let mut cmd = None;
        match rng.random(1000) {
            0..=4 => cmd = Some(format!(">chat turn talk {}", rng.random(100))),
            5 | 6 => cmd = Some(">requestlog".into()),
            7 => cmd = Some(">requestexport".into()),
            8 => cmd = Some(format!(">requestteam p{}", 1 + rng.random(2))),
            9 => cmd = Some(format!(">player p{} {{\"name\":\"Renamed{}\"}}", 1 + rng.random(2), rng.random(10))),
            10 | 11 => {
                let sodium = rng.random(2) == 0;
                cmd = Some(format!(">reseed {}", random_seed_text(&mut rng, sodium)));
            }
            12 => cmd = Some(format!(">forcewin p{}", 1 + rng.random(2))),
            13 => cmd = Some(">forcetie".into()),
            14 => cmd = Some(format!(">forcelose p{}", 1 + rng.random(2))),
            15 | 16 => cmd = Some(">tiebreak".into()),
            17 => cmd = Some(">version abc123".into()),
            18..=20 => cmd = Some(">show-openteamsheets".into()),
            _ => {}
        }
        if cmd.is_none() {
            let waiting: Vec<SideId> = SideId::BOTH.into_iter().filter(|&s| stream.waiting_for(s)).collect();
            let Some(&side) = waiting.get(rng.random(waiting.len().max(1) as u32) as usize) else {
                break;
            };
            let battle = stream.battle().expect("a battle while someone waits");
            let legal = battle.legal_actions(side);
            let names = &names[side.index()];
            let (real, _) = spell_choice(battle, side, legal.sample(&mut rng), names, &mut rng);
            let roll = rng.random(100);
            let text = if roll < probe_rate {
                probes_for(battle, side, &real, 1, &mut rng).pop().unwrap_or(real)
            } else {
                match roll - probe_rate {
                    0..=4 => spell_choice(battle, side, legal.sample(&mut rng), names, &mut rng).0,
                    5..=7 => "undo".into(),
                    8 | 9 => {
                        // Out of turn, or changing a stored choice.
                        let other = side.foe();
                        let what = ["move 1", "default", "undo", "switch 3"][rng.random(4) as usize];
                        let line = format!(">{} {what}", pikapro_protocol::side_id(other));
                        stream.write(&line).unwrap_or_else(|e| panic!("seed {seed}: {line}: {e}"));
                        commands.push(line);
                        continue;
                    }
                    _ => real,
                }
            };
            let line = format!(">{} {text}", pikapro_protocol::side_id(side));
            stream.write(&line).unwrap_or_else(|e| panic!("seed {seed}: {line}: {e}"));
            commands.push(line);
            // A stored choice changed or undone before the other player's.
            if !stream.waiting_for(side) && stream.waiting_for(side.foe()) && rng.random(10) == 0 {
                let battle = stream.battle().expect("a battle");
                let again = match rng.random(3) {
                    0 => "undo".to_string(),
                    1 => probes_for(battle, side, &text, 1, &mut rng).pop().unwrap_or(text),
                    _ => text,
                };
                cmd = Some(format!(">{} {again}", pikapro_protocol::side_id(side)));
            } else {
                continue;
            }
        }
        let cmd = cmd.expect("chosen above");
        stream.write(&cmd).unwrap_or_else(|e| panic!("seed {seed}: {cmd}: {e}"));
        commands.push(cmd);
    }
    if !stream.battle_ended() {
        commands.push(">forcetie".into());
    }
    if rng.random(3) == 0 {
        commands.push(">p1 move 1".into());
    }
    commands
}

/// `--hidden`: what makes Showdown hide or reveal information when a
/// choice is rejected. Trapping abilities (`maybeTrapped`), Imprison
/// (`maybeDisabled`, `maybeLocked`), visible disables (Taunt, Encore,
/// Disable, Torment, choice items, Assault Vest) on random Pokémon.
fn force_hidden(format: &Format, teams: &mut [pikapro::Team; 2], rng: &mut BattleRng) {
    use pikapro_conformance::{IMPLEMENTED_ABILITIES, item_pool, move_pool};
    use pikapro_data::gen9::{abilities, items, moves};
    let move_ok = move_pool(format);
    let item_ok = item_pool(format);
    let traps = [abilities::SHADOW_TAG, abilities::ARENA_TRAP, abilities::MAGNET_PULL];
    let disables = [moves::IMPRISON, moves::TAUNT, moves::ENCORE, moves::DISABLE, moves::TORMENT, moves::IMPRISON];
    let held = [items::CHOICE_SCARF, items::CHOICE_BAND, items::CHOICE_SPECS, items::ASSAULT_VEST];
    // Items may repeat: the stream plays unvalidated teams.
    for team in teams.iter_mut() {
        for set in team.sets.iter_mut() {
            match rng.random(6) {
                0 => {
                    let a = traps[rng.random(3) as usize];
                    if IMPLEMENTED_ABILITIES.contains(&a) {
                        set.ability = a;
                    }
                }
                1 | 2 => {
                    let m = disables[rng.random(disables.len() as u32) as usize];
                    if move_ok.contains(&m) && !set.moves.contains(&m) && !set.moves.is_empty() {
                        let k = rng.random(set.moves.len() as u32) as usize;
                        set.moves[k] = m;
                    }
                }
                3 => {
                    let it = held[rng.random(held.len() as u32) as usize];
                    if item_ok.contains(&it) {
                        set.item = Some(it);
                    }
                }
                _ => {}
            }
        }
    }
}

/// Groups commands into writes: one each, or random chunks with comments
/// and blank lines (sometimes the whole script at once).
///
/// In a custom game (`debug`), chunks have at most two commands: Showdown
/// sends an update in the middle of a write once more than 500 log lines
/// wait (`commitChoices`), and it counts its `|debug|` lines, which
/// pikapro does not write, so a long chunk may be split elsewhere.
fn writes_for(commands: &[String], batch: bool, debug: bool, rng: &mut BattleRng) -> Vec<String> {
    if !batch {
        return commands.to_vec();
    }
    if !debug && rng.random(6) == 0 {
        return vec![commands.join("\n")];
    }
    let mut out = Vec::new();
    let mut i = 0;
    while i < commands.len() {
        let n = 1 + rng.random(if debug { 2 } else { 8 }) as usize;
        let mut lines: Vec<String> = Vec::new();
        for c in &commands[i..(i + n).min(commands.len())] {
            match rng.random(12) {
                0 => lines.push(String::new()),
                1 => lines.push("# a comment".into()),
                _ => {}
            }
            lines.push(c.clone());
        }
        out.push(lines.join("\n"));
        i += n;
    }
    out
}

/// A script's commands as `getPlayerStreams` writes: choices to the
/// players' channels, everything else to the omniscient one.
fn channel_writes(commands: &[String]) -> Vec<(String, String)> {
    commands
        .iter()
        .map(|c| match (c.strip_prefix(">p1 "), c.strip_prefix(">p2 ")) {
            (Some(rest), _) => ("p1".to_string(), rest.to_string()),
            (_, Some(rest)) => ("p2".to_string(), rest.to_string()),
            _ => ("omniscient".to_string(), c.clone()),
        })
        .collect()
}

struct Theirs {
    messages: Vec<String>,
    error: Option<String>,
    channels: Option<Vec<(String, String)>>,
}

fn oracle_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tools/showdown-oracle")
}

/// `--cli`: the script as a file on the standard input of `pokemon-showdown
/// simulate-battle` and of `pikapro-simulate` (both read a file in 64 KiB
/// chunks, so both write the same chunks); `|t:|` times left out.
fn run_clis(case: &Case, dir: &Path) -> Option<String> {
    let path = dir.join("cli-script.txt");
    std::fs::write(&path, case.commands.join("\n") + "\n").expect("write the script");
    let flag = match case.replay {
        Some("spectator") => Some("--spectate"),
        Some(_) => Some("--replay"),
        None => None,
    };
    let run = |mut cmd: Command| -> String {
        cmd.args(flag).stdin(std::fs::File::open(&path).expect("the script"));
        let out = cmd.output().expect("the tool runs");
        let text = String::from_utf8_lossy(&out.stdout);
        let lines: Vec<&str> = text.split('\n').map(|l| if l.starts_with("|t:|") { "|t:|" } else { l }).collect();
        format!("status {:?}\n{}", out.status.code(), lines.join("\n"))
    };
    let mut showdown = Command::new("node");
    showdown
        .arg(oracle_dir().join("node_modules/pokemon-showdown/pokemon-showdown"))
        .args(["simulate-battle", "--skip-build"]);
    let theirs = run(showdown);
    // The binary of the same profile and target directory: this example
    // runs from `<target>/<profile>/examples/`. Cargo doesn't build a
    // package's binaries for its examples.
    let exe = std::env::current_exe().expect("this example's path");
    let exe = exe.parent().and_then(Path::parent).expect("the profile directory").join("pikapro-simulate");
    assert!(
        exe.exists(),
        "--cli runs {}: build it first, with `cargo build --release -p pikapro-server`",
        exe.display()
    );
    let ours = run(Command::new(exe));
    first_difference(&[ours], &[theirs]).map(|d| format!("cli: {d}"))
}

/// Runs the cases on Showdown's `BattleStream`.
fn run_showdown(cases: &[Case], dir: &Path) -> Vec<Theirs> {
    let input = Json::Array(
        cases
            .iter()
            .map(|c| {
                let mut o = Json::object();
                o.set("writes", Json::Array(c.writes.iter().map(|w| Json::str(w.clone())).collect()));
                o.set("keepAlive", Json::Bool(c.keep_alive));
                match c.replay {
                    Some("spectator") => o.set("replay", Json::str("spectator")),
                    Some(_) => o.set("replay", Json::Bool(true)),
                    None => {}
                }
                if let Some(ch) = &c.channel_writes {
                    let list = ch.iter().map(|(n, w)| Json::Array(vec![Json::str(n.clone()), Json::str(w.clone())]));
                    o.set("channels", Json::Array(list.collect()));
                }
                o
            })
            .collect(),
    );
    let path = dir.join("batch.json");
    std::fs::write(&path, input.stringify()).expect("write the batch");
    let out = Command::new("node")
        .arg(oracle_dir().join("stream.mjs"))
        .arg(&path)
        .stdin(Stdio::null())
        .output()
        .expect("node runs");
    assert!(out.status.success(), "stream.mjs failed: {}", String::from_utf8_lossy(&out.stderr));
    let results = Json::parse(String::from_utf8_lossy(&out.stdout).trim()).expect("stream.mjs writes JSON");
    let strings = |v: Option<&Json>| -> Vec<String> {
        v.and_then(Json::as_array)
            .map_or(Vec::new(), |a| a.iter().filter_map(|s| s.as_str().map(String::from)).collect())
    };
    results
        .as_array()
        .expect("an array")
        .iter()
        .map(|r| Theirs {
            messages: strings(r.get("messages")),
            error: r.get("error").and_then(Json::as_str).map(String::from),
            channels: r.get("channels").map(|ch| {
                transcript::CHANNELS
                    .iter()
                    .flat_map(|name| strings(ch.get(name)).into_iter().map(move |c| (name.to_string(), c)))
                    .collect()
            }),
        })
        .collect()
}

/// The fuzzer's cases for a range of seeds.
fn cases_for(a: &Args, seeds: &[u64], rng: &mut BattleRng) -> Vec<Case> {
    seeds
        .iter()
        .map(|&seed| {
            let mut commands = generate(&a.format, a.formatid.as_deref(), seed, a.sodium, a.hidden, a.generated);
            let debug = script_debug(&commands);
            // Stream options: after the end, a kept-alive stream still
            // answers; a replay stream sends only one channel's updates.
            let keep_alive = rng.random(6) == 0;
            if keep_alive {
                for c in [">p1 move 1", ">chat after the end", ">forcewin p1", ">tiebreak", ">requestlog", ">p2 undo"] {
                    commands.push(c.into());
                }
            }
            let replay = match rng.random(12) {
                0 => Some("omniscient"),
                1 => Some("spectator"),
                _ => None,
            };
            let batch = match a.mode {
                Mode::Lines => false,
                Mode::Batch => true,
                Mode::Mixed => rng.random(2) == 0,
            };
            let writes = writes_for(&commands, batch, debug, rng);
            let channel_writes = (a.channels > 0 && seed % a.channels == 0).then(|| channel_writes(&commands));
            let channel_writes = channel_writes.filter(|_| !keep_alive && replay.is_none());
            let mode = if batch { "batch" } else { "lines" };
            Case {
                name: format!(
                    "{}-{}{}-{seed}-{mode}",
                    a.formatid.as_deref().unwrap_or(a.format.id),
                    if a.sodium { "sodium" } else { "gen5" },
                    if a.generated { "-generated" } else { "" }
                ),
                debug,
                seed,
                keep_alive,
                replay,
                commands,
                writes,
                channel_writes,
            }
        })
        .collect()
}

/// `--edge`: hand-written scripts for what random ones rarely reach:
/// Showdown's exceptions (reported as errors), commands before the battle,
/// seeds as arrays, odd spellings, `strictChoices`, a second `>start`.
fn edge_cases() -> Vec<Case> {
    let singles = "Pikachu||choicespecs|static|thunderbolt,quickattack|Timid|,,,252,,252||||50|";
    let snorlax = "Snorlax||leftovers|thickfat|rest,bodyslam,imprison|Timid|,,,252,,252||||50|";
    let custom = "gen9customgame@@@!Team Preview";
    let start = |seed: &str| format!(">start {{\"formatid\":\"{custom}\",\"seed\":{seed}}}");
    let players = [
        format!(">player p1 {{\"name\":\"A\",\"team\":\"{singles}\"}}"),
        format!(">player p2 {{\"name\":\"B\",\"team\":\"{snorlax}\"}}"),
    ];
    let s = |v: &[&str]| -> Vec<String> { v.iter().map(|x| x.to_string()).collect() };
    let seeded = start("\"gen5,00010002000300ff\"");
    let with_players = |more: &[&str]| -> Vec<String> {
        let mut v = vec![seeded.clone(), players[0].clone(), players[1].clone()];
        v.extend(more.iter().map(|x| x.to_string()));
        v
    };
    let json_team = format!(
        ">player p1 {{\"name\":\"J\",\"team\":{}}}",
        quote(&format!(
            "[{}]",
            r#"{"name":"","species":"pikachu","item":"Light Ball","ability":"Static","moves":["thunderbolt","Quick Attack"],"evs":{"spa":252,"spe":"252"},"ivs":{"atk":0},"level":"50","gender":"F"}"#
        ))
    );
    let cases: Vec<(&str, bool, Vec<String>)> = vec![
        ("unknown-command", false, vec![seeded.clone(), ">foo bar".into()]),
        ("choice-before-start", false, s(&[">p1 move 1"])),
        ("chat-before-start", false, s(&[">chat hi"])),
        ("undo-before-start", false, s(&[">p1 undo"])),
        ("forcewin-before-start", false, s(&[">forcewin p1"])),
        ("p3-choice", false, with_players(&[">p3 move 1"])),
        ("team-twice", false, vec![seeded.clone(), players[0].clone(), players[0].clone()]),
        ("requestteam-p3", false, with_players(&[">requestteam p3"])),
        ("requestteam-x", false, with_players(&[">requestteam x"])),
        ("requestteam-before-p2", false, vec![seeded.clone(), players[0].clone(), ">requestteam p2".into()]),
        ("bad-reseed", false, with_players(&[">reseed xyz"])),
        ("tiebreak-before-p2", false, vec![seeded.clone(), players[0].clone(), ">tiebreak".into()]),
        (
            "one-player",
            false,
            vec![
                seeded.clone(),
                players[0].clone(),
                ">p1 move 1".into(),
                ">p1 undo".into(),
                ">requestlog".into(),
                ">requestexport".into(),
                ">requestteam p1".into(),
                ">p2 move 1".into(),
            ],
        ),
        (
            "strict-choices",
            false,
            vec![
                format!(">start {{\"formatid\":\"{custom}\",\"seed\":\"sodium,01\",\"strictChoices\":true}}"),
                players[0].clone(),
                players[1].clone(),
                ">p1 move 1".into(),
                ">p1 move 9".into(),
                ">p2 move 1".into(),
            ],
        ),
        ("seed-array", false, {
            let mut v = vec![start("[1,2,3,65535]"), players[0].clone(), players[1].clone()];
            v.extend(s(&[">p1 move 1", ">p2 move 2", ">requestexport", ">forcelose p2"]));
            v
        }),
        ("seed-numbers", false, {
            let mut v = vec![start("\"1,2,3,4\""), players[0].clone(), players[1].clone()];
            v.extend(s(&[">p1 move 2", ">p2 move 1", ">tiebreak"]));
            v
        }),
        ("seed-sodium-odd", false, {
            let mut v = vec![start("\"sodium,xyz-1 0fa9G,ignored\""), players[0].clone(), players[1].clone()];
            v.extend(s(&[
                ">p1 move 1",
                ">p2 move 1",
                ">reseed sodium,ab",
                ">p1 move 1",
                ">p2 move 2",
                ">requestlog",
                ">forcetie",
            ]));
            v
        }),
        ("start-twice", false, {
            let mut v = with_players(&[">p1 move 1"]);
            v.push(start("\"gen5,0000000000000001\""));
            v.extend(players.iter().cloned());
            v.extend(s(&[">p1 move 1", ">p2 move 2", ">forcewin p2"]));
            v
        }),
        ("json-team", false, {
            let mut v = vec![seeded.clone(), json_team.clone(), players[1].clone()];
            v.extend(s(&[">p1 move 1", ">p2 move 1", ">requestteam p1", ">forcewin p1"]));
            v
        }),
        (
            "spellings",
            false,
            with_players(&[
                ">p1 move 1\r",
                ">p2   move   bodyslam  ",
                ">p1 move Thunderbolt 1",
                ">p1 move thunderbolt terastal",
                "not a command",
                "",
                ">p2 move 2, move 1",
                ">p2 move imprison",
                ">p1 move quickattack",
                ">p1 testfight",
                ">p1 default",
                ">p2 undo",
                ">p2 undo",
                ">p2 default",
                ">chat bye | pipes \u{2028} and all",
                ">chat-inputlogonly hidden",
                ">version-origin x",
                ">requestlog",
                ">forcelose p1",
            ]),
        ),
        ("open-team-sheets", false, {
            let vgc = "gen9doublescustomgame@@@Picked Team Size = 4,Adjust Level Down = 50";
            let mut v = vec![format!(">start {{\"formatid\":\"{vgc}\",\"seed\":\"sodium,77\"}}")];
            // Two Pokémon each: Showdown crashes on a doubles battle with one.
            let pair = format!("{singles}]{snorlax}");
            v.push(format!(">player p1 {{\"name\":\"A\",\"team\":\"{pair}\"}}"));
            v.push(format!(">player p2 {{\"name\":\"B\",\"team\":\"{pair}\",\"rating\":1000}}"));
            v.extend(s(&[">show-openteamsheets", ">p1 team 21", ">p2 team 12", ">show-openteamsheets", ">forcetie"]));
            v
        }),
        ("open-team-sheets-crowned", false, {
            // `showOpenTeamSheets` shows Zacian and Zamazenta holding their
            // Rusted items as the Crowned formes with the signature move for
            // Iron Head, and the rewrite reaches the sets themselves
            // (`>requestteam`, the `end` log).
            let vgc = "gen9doublescustomgame@@@Picked Team Size = 4,Adjust Level Down = 50";
            let zacian =
                "Zacian||rustedsword|intrepidsword|playrough,ironhead,sacredsword,protect|Jolly|,252,,,4,252||||50|";
            let zamazenta = "Zamazenta||rustedshield|dauntlessshield|ironhead,bodypress|Impish|252,,252,,4,||||50|";
            let mut v = vec![format!(">start {{\"formatid\":\"{vgc}\",\"seed\":\"sodium,78\"}}")];
            v.push(format!(">player p1 {{\"name\":\"A\",\"team\":\"{zacian}]{singles}\"}}"));
            v.push(format!(">player p2 {{\"name\":\"B\",\"team\":\"{snorlax}]{zamazenta}\"}}"));
            v.extend(s(&[">requestteam p1", ">show-openteamsheets", ">requestteam p1", ">requestteam \u{e9}2"]));
            v.extend(s(&[">show-openteamsheets", ">forcetie"]));
            v
        }),
        // `message.slice(1)` cuts a UTF-16 unit: an astral first character
        // leaves half a surrogate pair, which `parseInt` reads as NaN.
        ("requestteam-utf16", false, with_players(&[">requestteam \u{e9}1", ">requestteam \u{1F600}2", ">forcetie"])),
        (
            "reseed-between-players",
            false,
            vec![
                seeded.clone(),
                players[1].clone(),
                ">reseed sodium,1234".into(),
                players[0].clone(),
                ">p1 move 1".into(),
                ">p2 move 1".into(),
                ">forcetie".into(),
            ],
        ),
        (
            "rename",
            false,
            with_players(&[
                ">player p1 {\"name\":\"A\"}",
                ">player p1 {\"name\":\"Zed\",\"avatar\":2,\"rating\":1234}",
                ">player p2 {\"avatar\":\"lucas\"}",
                ">p1 move 1",
                ">p2 move 1",
                ">forcewin p1",
            ]),
        ),
        (
            "keep-alive-after-end",
            true,
            with_players(&[
                ">forcewin x2",
                ">p1 move 1",
                ">p2 undo",
                ">forcetie",
                ">tiebreak",
                ">forcelose p1",
                ">reseed gen5,0000000000000002",
                ">chat still here",
                ">requestlog",
            ]),
        ),
    ];
    cases
        .into_iter()
        .map(|(name, keep_alive, commands)| Case {
            name: format!("edge-{name}"),
            debug: script_debug(&commands),
            seed: 0,
            keep_alive,
            replay: None,
            writes: commands.clone(),
            // Through `getPlayerStreams` too, where Showdown throws nothing.
            channel_writes: [
                "spellings",
                "rename",
                "seed-array",
                "seed-numbers",
                "seed-sodium-odd",
                "json-team",
                "start-twice",
                "open-team-sheets",
            ]
            .contains(&name)
            .then(|| channel_writes(&commands)),
            commands,
        })
        .collect()
}

/// The comment a recorded transcript starts with: its name, how it was
/// recorded, and the Showdown it was recorded from.
fn provenance(name: &str) -> String {
    format!("{name}: `cargo run -p pikapro-server --example stream_fuzz`, Showdown master a5df827")
}

/// Whether `comment` is a transcript's [`provenance`] line, as this or an
/// earlier version of the tool wrote it.
fn is_provenance(comment: &str, name: &str) -> bool {
    comment.strip_prefix(name).and_then(|c| c.strip_prefix(": `cargo run -p ")).is_some_and(|c| {
        c.split_once('`').is_some_and(|(command, rest)| {
            command.ends_with(" --example stream_fuzz") && rest.starts_with(", Showdown ")
        })
    })
}

/// `--rerecord DIR`: each transcript's script replayed on Showdown; the
/// ones pikapro-server still matches are rewritten with Showdown's messages
/// (and their provenance comment brought up to date).
fn rerecord(record: &Path, dir: &Path) {
    let files = pikapro_conformance::fixture::check_manifest(record, "txt").unwrap_or_else(|e| panic!("{e}"));
    let transcripts: Vec<(PathBuf, Transcript)> = files
        .into_iter()
        .map(|p| {
            let text = std::fs::read_to_string(&p).expect("a transcript");
            let t = Transcript::parse(&text).unwrap_or_else(|e| panic!("{}: {e}", p.display()));
            (p, t)
        })
        .collect();
    let cases: Vec<Case> = transcripts
        .iter()
        .map(|(p, t)| Case {
            name: p.file_stem().expect("a name").to_string_lossy().into_owned(),
            debug: script_debug(&t.writes),
            seed: 0,
            keep_alive: t.keep_alive,
            replay: match t.replay.as_deref() {
                Some("spectator") => Some("spectator"),
                Some(_) => Some("omniscient"),
                None => None,
            },
            commands: Vec::new(),
            writes: t.writes.clone(),
            channel_writes: (!t.channel_writes.is_empty()).then(|| t.channel_writes.clone()),
        })
        .collect();
    let (mut passed, mut failed) = (0, 0);
    for ((path, old), (case, theirs)) in transcripts.iter().zip(cases.iter().zip(run_showdown(&cases, dir))) {
        let options = transcript::options(case.keep_alive, case.replay);
        let (ours, our_error) = transcript::run_ours(&case.writes, options);
        let expected = normalize_messages(&theirs.messages, case.debug);
        let mut problem = first_difference(&ours, &expected);
        if problem.is_none() && our_error != theirs.error {
            problem = Some(format!("error: ours {our_error:?}, theirs {:?}", theirs.error));
        }
        let mut channels = None;
        if problem.is_none()
            && let (Some(writes), Some(theirs)) = (&case.channel_writes, &theirs.channels)
        {
            let ours = transcript::run_channels(writes);
            let theirs = normalize_chunks(theirs, case.debug);
            let a: Vec<String> = ours.iter().map(|(n, c)| format!("[{n}] {c}")).collect();
            let b: Vec<String> = theirs.iter().map(|(n, c)| format!("[{n}] {c}")).collect();
            problem = first_difference(&a, &b).map(|d| format!("channels: {d}"));
            channels = Some(theirs);
        }
        match problem {
            None => {
                passed += 1;
                let comments = old
                    .comments
                    .iter()
                    .map(|c| if is_provenance(c, &case.name) { provenance(&case.name) } else { c.clone() })
                    .collect();
                let t = Transcript {
                    comments,
                    messages: expected,
                    error: theirs.error,
                    channels: channels.unwrap_or_default(),
                    ..old.clone()
                };
                std::fs::write(path, t.write()).expect("write the transcript");
            }
            Some(p) => {
                failed += 1;
                println!("FAIL {} \n{p}\n", case.name);
            }
        }
    }
    println!("rerecord: {passed} passed and rewritten, {failed} failed");
}

fn main() {
    let a = args();
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../target/stream-fuzz");
    std::fs::create_dir_all(&dir).expect("create target/stream-fuzz");
    if let Some(record) = &a.rerecord {
        rerecord(record, &dir);
        return;
    }
    let formatid = a.formatid.as_deref().unwrap_or_else(|| showdown_format(&a.format).expect("a Showdown format"));
    assert!(pikapro_server::format::resolve(formatid).is_some(), "unknown format {formatid}");
    let mut rng = BattleRng::new(Seed::fast(a.seed ^ 0x5354_5245));
    let mut passed = 0;
    let mut failed = 0;
    let mut shown = 0;
    // What the passing scripts covered: (what, needle, count).
    let mut coverage: Vec<(&str, &str, usize)> = vec![
        ("choice errors", "|error|[Invalid choice]", 0),
        ("trapped", "is trapped", 0),
        ("disabled", "is disabled", 0),
        ("unavailable choices", "|error|[Unavailable choice]", 0),
        ("updated requests", "\"update\":true", 0),
        ("can't undo", "Can't undo", 0),
        ("not your turn", "It's not your turn", 0),
        ("game over", "The game is over", 0),
        ("requested data", "requesteddata\n", 0),
        ("wins", "|win|", 0),
        ("ties", "\"winner\":\"\"", 0),
        ("tiebreaks", "Going to tiebreaker", 0),
        ("reseeds", "RNG was reset", 0),
        ("chats", "|chat|", 0),
        ("team previews", "|teampreview", 0),
        ("end logs", "end\n{", 0),
        ("rated", "|rated|", 0),
    ];
    let mut channel_cases = 0;
    let seeds: Vec<u64> = (a.seed..a.seed + a.battles).collect();
    let batches: Vec<Vec<Case>> = if a.edge {
        vec![edge_cases()]
    } else {
        seeds.chunks(25).map(|chunk| cases_for(&a, chunk, &mut rng)).collect()
    };
    for cases in batches {
        let theirs = run_showdown(&cases, &dir);
        for (case, theirs) in cases.iter().zip(theirs) {
            let debug = case.debug;
            let options = transcript::options(case.keep_alive, case.replay);
            let (ours, our_error) = transcript::run_ours(&case.writes, options);
            let expected = normalize_messages(&theirs.messages, debug);
            let mut problem = first_difference(&ours, &expected);
            if problem.is_none() && our_error != theirs.error {
                problem = Some(format!("error: ours {our_error:?}, theirs {:?}", theirs.error));
            }
            if problem.is_none() && !a.edge && (case.seed - a.seed) < a.cli {
                problem = run_clis(case, &dir);
            }
            let mut channels = None;
            if problem.is_none()
                && let (Some(writes), Some(theirs)) = (&case.channel_writes, &theirs.channels)
            {
                let ours = transcript::run_channels(writes);
                let theirs = normalize_chunks(theirs, debug);
                let a: Vec<String> = ours.iter().map(|(n, c)| format!("[{n}] {c}")).collect();
                let b: Vec<String> = theirs.iter().map(|(n, c)| format!("[{n}] {c}")).collect();
                problem = first_difference(&a, &b).map(|d| format!("channels: {d}"));
                channels = Some(theirs);
            }
            let name = &case.name;
            match problem {
                None => {
                    passed += 1;
                    for (_, needle, count) in &mut coverage {
                        *count += expected.iter().map(|m| m.matches(*needle).count()).sum::<usize>();
                    }
                    channel_cases += usize::from(channels.is_some());
                    if let Some(record) = &a.record {
                        let t = Transcript {
                            keep_alive: case.keep_alive,
                            replay: case.replay.map(String::from),
                            comments: vec![provenance(name)],
                            writes: case.writes.clone(),
                            messages: expected,
                            error: theirs.error.clone(),
                            channel_writes: case.channel_writes.clone().unwrap_or_default(),
                            channels: channels.unwrap_or_default(),
                        };
                        std::fs::create_dir_all(record).expect("create the record directory");
                        let file = format!("{name}.txt");
                        if !pikapro_conformance::fixture::record(record, &file, &t.write())
                            .expect("record the transcript")
                        {
                            eprintln!("{file} exists: not overwritten (`--rerecord` rewrites transcripts)");
                        }
                    }
                }
                Some(p) => {
                    failed += 1;
                    let path = dir.join(format!("{name}.txt"));
                    std::fs::write(&path, case.commands.join("\n") + "\n").expect("save the script");
                    if shown < a.show {
                        shown += 1;
                        println!("FAIL {name} ({} commands, script: {})\n{p}\n", case.commands.len(), path.display());
                    }
                }
            }
        }
        print!("\r{passed} passed, {failed} failed");
        let _ = std::io::stdout().flush();
    }
    println!();
    let covered: Vec<String> = coverage.iter().map(|(what, _, n)| format!("{what} {n}")).collect();
    println!("covered: {}, channel scripts {channel_cases}", covered.join(", "));
    if failed > 0 {
        std::process::exit(1);
    }
}
