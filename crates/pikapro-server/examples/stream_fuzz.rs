//! Differential fuzzer for the battle stream: random command
//! scripts run on pikapro-server's `BattleStream` and on Showdown's
//! (`tools/showdown-oracle/stream.mjs`), every message compared.
//!
//! ```sh
//! cargo run --release -p pikapro-server --example stream_fuzz -- \
//!     --format championsvgc --battles 200 --seed 2100000 [--sodium] \
//!     [--mode lines|batch|mixed] [--channels N] [--show 3] [--record DIR] \
//!     [--formatid gen9vgc2025regi] [--hidden] [--cli N] [--edge] [--generated]
//! cargo run --release -p pikapro-server --example stream_fuzz -- --rerecord DIR
//! ```
//!
//! A script is generated by driving pikapro-server's stream itself: random
//! teams (the conformance generator's), a `>start` with a Showdown format
//! id (sometimes the preset's own) and a `gen5` or `sodium` seed, the
//! players (sometimes inline in `>start`, sometimes as JSON teams), then
//! whatever each waiting player does (`--formatid` names the Showdown
//! format instead, played with the preset's teams; `gen9vgc2025regi` for
//! `gen9vgc`): a random legal choice spelled one of
//! Showdown's ways, other spellings and invalid choices
//! (`choices::probes_for`), a choice changed or undone before the other
//! player's, a choice out of turn, and now and then `>chat`,
//! `>requestlog`, `>requestexport`, `>requestteam`, a rename, `>reseed`,
//! or an early end (`>forcewin`, `>forcetie`, `>forcelose`, `>tiebreak`).
//! With `--generated` (the random battles), the players bring no team but
//! a `gen5` or `sodium` seed, and both streams draw their teams with the
//! format's generator.
//! The script is then replayed one command per write (`lines`), or in
//! random chunks with comments and blank lines (`batch`), and with
//! `--channels N`, every Nth script also through `getPlayerStreams`, the
//! choices written to the players' channels.
//!
//! Compared: every message, `|t:|` times left out; in custom-game formats
//! Showdown's `|debug|` lines are dropped (pikapro writes none). With
//! `--record DIR`, passing scripts are written there as golden transcripts
//! (`tests/transcripts.rs` replays them). `--rerecord DIR` replays each
//! transcript's script in `DIR` on Showdown and rewrites the ones that
//! pass with what Showdown sends now (after a change of the pinned
//! Showdown), keeping their comments.

